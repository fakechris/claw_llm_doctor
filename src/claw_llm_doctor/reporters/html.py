def pct(v: float) -> str:
    return f"{v * 100:.1f}%"


def health_badge(health: str) -> str:
    colors = {"green": "#22c55e", "yellow": "#eab308", "red": "#ef4444"}
    return f'<span class="badge" style="background:{colors.get(health, "#888")}"></span>'


def severity_badge(sev: str) -> str:
    colors = {"none": "#22c55e", "low": "#eab308", "medium": "#f97316", "high": "#ef4444"}
    return f'<span class="badge" style="background:{colors.get(sev, "#888")}"></span>'


