def generate_html(
    routing: RoutingReport | None = None,
    contexts: list[ContextReport] | None = None,
    prompt_orders: list[PromptOrderReport] | None = None,
    compressions: list[CompressionReport] | None = None,
    thinkings: list[ThinkingReport] | None = None,
    performances: list[PerformanceReport] | None = None,
) -> str:
    sections: list[str] = []

    if routing:
        sections.append(render_routing(routing))
    if contexts:
        for c in contexts:
            sections.append(render_context(c))
    if prompt_orders:
        for p in prompt_orders:
            sections.append(render_prompt_order(p))
    if compressions:
        for c in compressions:
            sections.append(render_compression(c))
    if thinkings:
        for t in thinkings:
            sections.append(render_thinking(t))
    if performances:
        for p in performances:
            sections.append(render_performance(p))

    return HTML_TEMPLATE.replace("{content}", "\n".join(sections))


def write_html(html: str, output: str) -> None:
    with open(output, "w") as f:
        f.write(html)


def _esc(s: Any) -> str:
    """Escape HTML special characters."""
    return (str(s)
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;")
            .replace("'", "&#x27;"))
