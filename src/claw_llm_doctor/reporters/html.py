def render_routing(report: RoutingReport) -> str:
    d = routing_to_dict(report)
    s = d["summary"]
    html = '<h2>Layer 1: LM Routing Analysis</h2><div class="card">'

    # Primary model info
    if report.primary_model:
        html += f'<div class="metric"><div class="label">Primary Model</div><div class="value">{_esc(report.primary_model)}</div></div>'

    # Summary metrics
    metrics = [
        ("Total Calls", s["total_calls"]),
        ("Primary", s["primary_calls"]),
        ("Fallback", s["fallback_calls"]),
        ("Primary OK", pct(s["primary_success_rate"])),
        ("Fallback OK", pct(s["fallback_success_rate"])),
        ("Overall OK", pct(s["overall_success_rate"])),
        ("Fallback Rate", pct(s["fallback_trigger_rate"])),
    ]
    for label, val in metrics:
        html += f'<div class="metric"><div class="label">{label}</div><div class="value">{val}</div></div>'
    html += "</div>"

    # Model table
    if d["by_model"]:
        html += "<h3>By Model</h3><table><tr><th>Model</th><th class='num'>Total</th>"
        html += "<th class='num'>Success</th><th class='num'>Failure</th></tr>"
        for model, info in d["by_model"].items():
            html += f"<tr><td>{_esc(model)}</td><td class='num'>{info['total']}</td>"
            html += f"<td class='num'>{info['success']}</td><td class='num'>{info['failure']}</td></tr>"
        html += "</table>"

    # Error table
    if d["errors"]:
        html += "<h3>Errors</h3><table><tr><th>Code</th><th class='num'>Count</th>"
        html += "<th>Models</th><th>Example</th></tr>"
        for code, info in sorted(d["errors"].items(), key=lambda x: -x[1]["count"]):
            example = info["examples"][0] if info["examples"] else ""
            html += f"<tr><td><span class='tag tag-red'>{_esc(code)}</span></td>"
            html += f"<td class='num'>{info['count']}</td>"
            html += f"<td>{_esc(', '.join(info['models']))}</td><td>{_esc(example)}</td></tr>"
        html += "</table>"

    # Session table
    if d["sessions"]:
        html += "<h3>Sessions</h3><table><tr><th>Session</th><th class='num'>Calls</th>"
        html += "<th class='num'>OK</th><th class='num'>Fail</th><th class='num'>Fallback</th></tr>"
        for sess in d["sessions"]:
            html += f"<tr><td>{_esc(sess['session_key'][:30])}</td>"
            html += f"<td class='num'>{sess['total_calls']}</td>"
            html += f"<td class='num'>{sess['success']}</td>"
            html += f"<td class='num'>{sess['failure']}</td>"
            html += f"<td class='num'>{sess['fallback_triggered']}</td></tr>"
        html += "</table>"

    if report.timeline:
        total_entries = len(report.timeline)
        cap = 30
        if total_entries > cap:
            display_entries = report.timeline[:15] + report.timeline[-15:]
            omitted = total_entries - cap
            title = f"Routing Timeline ({cap} of {total_entries})"
        else:
            display_entries = report.timeline
            omitted = 0
            title = f"Routing Timeline ({total_entries})"

        html += f"<h3>{_esc(title)}</h3><table><tr><th>Time</th><th>Session</th>"
        html += "<th>Model</th><th>Provider</th><th>Role</th><th>OK</th><th>Duration</th></tr>"
        for idx, e in enumerate(display_entries):
            if omitted and idx == 15:
                html += f'<tr><td colspan="7" style="text-align:center;color:var(--muted)">... {omitted} omitted ...</td></tr>'
            ts_str = datetime.fromtimestamp(e["timestamp"] / 1000).strftime("%m-%d %H:%M:%S")
            role = "Primary" if e["is_primary"] is True else ("Fallback" if e["is_primary"] is False else "?")
            role_cls = "tag-green" if e["is_primary"] is True else ("tag-yellow" if e["is_primary"] is False else "")
            ok = '<span class="tag tag-green">OK</span>' if e["success"] else '<span class="tag tag-red">FAIL</span>'
            dur = _esc(f'{e["duration_ms"]}ms') if e["duration_ms"] is not None else "-"
            html += f"<tr><td>{_esc(ts_str)}</td><td>{_esc(str(e['session_key'])[:20])}</td>"
            html += f"<td>{_esc(e['model'])}</td><td>{_esc(e['provider'])}</td>"
            html += f'<td><span class="tag {role_cls}">{role}</span></td>'
            html += f"<td>{ok}</td><td class='num'>{dur}</td></tr>"
        html += "</table>"

    if report.success_over_time:
        html += "<h3>Success Rate Over Time</h3>"
        html += "<table><tr><th>Time Window</th><th class='num'>Total</th>"
        html += "<th class='num'>Success</th><th class='num'>Rate</th></tr>"
        for bucket in report.success_over_time:
            start_str = _esc(datetime.fromtimestamp(bucket["bucket_start"] / 1000).strftime("%m-%d %H:%M"))
            end_str = _esc(datetime.fromtimestamp(bucket["bucket_end"] / 1000).strftime("%m-%d %H:%M"))
            rate = bucket["rate"]
            rate_cls = "tag-green" if rate >= 0.9 else ("tag-yellow" if rate >= 0.7 else "tag-red")
            html += f"<tr><td>{start_str}-{end_str}</td>"
            html += f"<td class='num'>{_esc(bucket['total'])}</td>"
            html += f"<td class='num'>{_esc(bucket['success'])}</td>"
            html += f"<td><span class='tag {rate_cls}'>{_esc(pct(rate))}</span></td></tr>"
        html += "</table>"

    if report.fallback_chains:
        html += f"<h3>Fallback Chains ({len(report.fallback_chains)})</h3>"
        for i, chain in enumerate(report.fallback_chains, 1):
            resolved = '<span class="tag tag-green">resolved</span>' if chain["final_success"] else '<span class="tag tag-red">unresolved</span>'
            models = " \u2192 ".join(chain["models_tried"])
            html += f'<div class="card"><strong>Chain {i}:</strong> {_esc(models)} {resolved}'
            html += "<table><tr><th class='num'>Step</th><th>Model</th><th>OK</th><th>Error</th><th class='num'>Duration</th></tr>"
            for step, call in enumerate(chain["calls"], 1):
                ok = '<span class="tag tag-green">OK</span>' if call["success"] else '<span class="tag tag-red">FAIL</span>'
                dur = _esc(f'{call["duration_ms"]}ms') if call["duration_ms"] is not None else "-"
                err = _esc((call.get("error") or "")[:60])
                html += f"<tr><td class='num'>{step}</td><td>{_esc(call['model'])}</td><td>{ok}</td><td>{err}</td><td class='num'>{dur}</td></tr>"
            html += "</table></div>"

    return html


def render_context(report: ContextReport) -> str:
    html = f'<h2>Layer 3a: Context \u2014 {_esc(report.session_key)}</h2><div class="card">'
    metrics = [
        ("Turns", len(report.turns)),
        ("Peak Util", pct(report.peak_utilization)),
        ("Avg Util", pct(report.avg_utilization)),
        ("Compactions", len(report.compaction_events)),
    ]
    for label, val in metrics:
        html += f'<div class="metric"><div class="label">{label}</div><div class="value">{val}</div></div>'
    html += "</div>"

    if report.turns:
        html += "<table><tr><th class='num'>Turn</th><th class='num'>System</th>"
        html += "<th class='num'>Tools</th><th class='num'>History</th>"
        html += "<th class='num'>ToolRes</th><th class='num'>Think</th>"
        html += "<th class='num'>Total</th><th class='num'>Util</th><th>HP</th></tr>"
        for t in report.turns:
            html += f"<tr><td class='num'>{t.turn_index}</td>"
            html += f"<td class='num'>{format_tokens(t.system_tokens)}</td>"
            html += f"<td class='num'>{format_tokens(t.tool_def_tokens)}</td>"
            html += f"<td class='num'>{format_tokens(t.history_tokens)}</td>"
            html += f"<td class='num'>{format_tokens(t.tool_result_tokens)}</td>"
            html += f"<td class='num'>{format_tokens(t.thinking_tokens)}</td>"
            html += f"<td class='num'>{format_tokens(t.total_tokens)}</td>"
            html += f"<td class='num'>{pct(t.utilization)}</td>"
            html += f"<td>{health_badge(t.health)}</td></tr>"
        html += "</table>"

    curve = report.growth_curve()
    if curve:
        max_tok = max((pt["total_tokens"] for pt in curve), default=1) or 1
        html += "<h3>Context Growth</h3>"
        for pt in curve:
            w = int((pt["total_tokens"] / max_tok) * 100)
            delta = pt["delta"]
            delta_color = "var(--green)" if delta >= 0 else "var(--red)"
            delta_str = f"+{delta}" if delta >= 0 else str(delta)
            html += f'<div class="sim-bar"><span class="idx">T{pt["turn_index"]}</span>'
            html += f'<div class="bar-container"><div class="bar-fill" style="width:{w}%;background:var(--accent)"></div></div>'
            html += f'<span>{format_tokens(pt["total_tokens"])}</span>'
            html += f'<span style="color:{delta_color}">{delta_str}</span></div>'

    return html


def render_prompt_order(report: PromptOrderReport) -> str:
    stable_tag = '<span class="tag tag-green">STABLE</span>' if report.is_stable else '<span class="tag tag-red">UNSTABLE</span>'
    html = f'<h2>Layer 3b: Prompt Order \u2014 {_esc(report.session_key)}</h2><div class="card">'
    html += f'<div class="metric"><div class="label">Turns</div><div class="value">{len(report.turns)}</div></div>'
    html += f'<div class="metric"><div class="label">Ordering</div><div class="value">{stable_tag}</div></div>'
    html += "</div>"

    if report.turns:
        html += f"<h3>Baseline: {_esc(report.turns[0].order_signature)}</h3>"

    if report.order_changes:
        html += "<h3>Order Changes</h3><table><tr><th class='num'>Turn</th><th>Before</th><th>After</th></tr>"
        for ch in report.order_changes:
            html += f"<tr><td class='num'>{ch['turn']}</td><td>{_esc(ch['prev_order'])}</td><td>{_esc(ch['curr_order'])}</td></tr>"
        html += "</table>"

    if report.missing_sections:
        html += "<h3>Missing Sections</h3><table><tr><th class='num'>Turn</th><th>Lost</th></tr>"
        for ms in report.missing_sections:
            tags = "".join(f'<span class="tag tag-red">{_esc(s)}</span>' for s in ms["missing"])
            html += f"<tr><td class='num'>{ms['turn']}</td><td>{tags}</td></tr>"
        html += "</table>"

    return html


def render_compression(report: CompressionReport) -> str:
    html = f'<h2>Layer 3c: Compression \u2014 {_esc(report.session_key)}</h2><div class="card">'
    metrics = [
        ("Baseline", f"{report.baseline_length:,} chars"),
        ("Sections", ", ".join(report.baseline_sections)),
        ("Max Loss", pct(report.max_loss_ratio)),
        ("Turns w/ Loss", report.turns_with_loss),
    ]
    for label, val in metrics:
        html += f'<div class="metric"><div class="label">{label}</div><div class="value">{val}</div></div>'
    html += "</div>"

    # Similarity curve
    if report.similarity_curve and len(report.similarity_curve) > 1:
        html += "<h3>Similarity vs Baseline</h3>"
        for i, sim in enumerate(report.similarity_curve):
            w = int(sim * 100)
            color = "#3fb950" if sim > 0.9 else "#d29922" if sim > 0.7 else "#f85149"
            html += f'<div class="sim-bar"><span class="idx">T{i}</span>'
            html += f'<div class="bar-container"><div class="bar-fill" style="width:{w}%;background:{color}"></div></div>'
            html += f"<span>{pct(sim)}</span></div>"

    if report.compactions:
        html += "<h3>Compaction Events</h3><table><tr><th class='num'>Turn</th>"
        html += "<th class='num'>Before</th><th class='num'>After</th>"
        html += "<th class='num'>Ratio</th><th>Lost Sections</th></tr>"
        for c in report.compactions:
            lost = "".join(f'<span class="tag tag-red">{_esc(s)}</span>' for s in c.lost_sections) or "-"
            html += f"<tr><td class='num'>{c.turn_index}</td>"
            html += f"<td class='num'>{c.before_length:,}</td>"
            html += f"<td class='num'>{c.after_length:,}</td>"
            html += f"<td class='num'>{pct(c.compression_ratio)}</td>"
            html += f"<td>{lost}</td></tr>"
        html += "</table>"

    return html


def render_thinking(report: ThinkingReport) -> str:
    html = f'<h2>Layer 3d: Thinking \u2014 {_esc(report.session_key)}</h2><div class="card">'
    metrics = [
        ("Thinking Turns", f"{report.turns_with_thinking}/{len(report.turns)}"),
        ("Thinking Ratio", pct(report.overall_thinking_ratio)),
        ("Think Tokens", format_tokens(report.total_thinking_tokens)),
        ("Content Tokens", format_tokens(report.total_content_tokens)),
        ("Leakage Turns", report.turns_with_leakage),
        ("Leakage Rate", pct(report.leakage_rate)),
    ]
    for label, val in metrics:
        html += f'<div class="metric"><div class="label">{label}</div><div class="value">{val}</div></div>'
    html += "</div>"

    # Leakage details
    if report.turns_with_leakage > 0:
        category_labels = {
            "tag_leak": "Tag Leak",
            "en_monologue": "EN Monologue",
            "cn_monologue": "CN Monologue",
            "interleave": "Token Interleaving",
        }

        if report.leakage_category_counts:
            html += "<h3>Leakage by Category</h3><table><tr><th>Category</th><th class='num'>Count</th></tr>"
            for cat, count in sorted(report.leakage_category_counts.items(), key=lambda x: -x[1]):
                html += f"<tr><td><span class='tag tag-red'>{_esc(category_labels.get(cat, cat))}</span></td><td class='num'>{count}</td></tr>"
            html += "</table>"

        html += "<h3>Leakage Pattern Details</h3><table><tr><th>Pattern</th><th>Category</th><th class='num'>Count</th></tr>"
        pattern_cats: dict[str, str] = {}
        for turn in report.turns:
            for li in turn.leakage_instances:
                pattern_cats[li.pattern_name] = li.category
        for name, count in sorted(report.leakage_pattern_counts.items(), key=lambda x: -x[1]):
            cat = pattern_cats.get(name, "?")
            html += f"<tr><td><span class='tag tag-red'>{_esc(name)}</span></td><td>{_esc(category_labels.get(cat, cat))}</td><td class='num'>{count}</td></tr>"
        html += "</table>"

        html += "<h3>Leakage Examples</h3>"
        for turn in report.turns:
            if turn.has_leakage:
                model_str = f" model={_esc(turn.model)}" if turn.model else ""
                ts_str = datetime.fromtimestamp(turn.ts / 1000).strftime("%m-%d %H:%M:%S") if turn.ts else "?"
                for li in turn.leakage_instances[:3]:
                    html += f'<div class="leak-example">Turn {turn.turn_index} <span style="color:var(--muted)">{ts_str}</span>{model_str} '
                    html += f'[{_esc(li.category)}/{_esc(li.pattern_name)}]: <code>{_esc(li.matched_text)}</code><br>'
                    html += f'{_esc(li.context)}</div>'

    # Per-turn table
    thinking_turns = [t for t in report.turns if t.has_thinking]
    if thinking_turns:
        html += "<h3>Thinking per Turn</h3><table><tr><th class='num'>Turn</th>"
        html += "<th>Time</th><th>Model</th>"
        html += "<th class='num'>Think</th><th class='num'>Content</th>"
        html += "<th class='num'>Ratio</th><th>Categories</th><th>Leak</th></tr>"
        for t in thinking_turns:
            cats = ", ".join(sorted({b.category for b in t.thinking_blocks}))
            ts_str = datetime.fromtimestamp(t.ts / 1000).strftime("%m-%d %H:%M:%S") if t.ts else "-"
            html += f"<tr><td class='num'>{t.turn_index}</td>"
            html += f"<td style='color:var(--muted)'>{ts_str}</td>"
            html += f"<td>{_esc(t.model or '?')}</td>"
            html += f"<td class='num'>{format_tokens(t.thinking_tokens)}</td>"
            html += f"<td class='num'>{format_tokens(t.content_tokens)}</td>"
            html += f"<td class='num'>{pct(t.thinking_ratio)}</td>"
            html += f"<td>{_esc(cats)}</td>"
            html += f"<td>{severity_badge(t.leakage_severity)}</td></tr>"
        html += "</table>"

    # Leakage by model
    leak_turns = [t for t in report.turns if t.has_leakage]
    if leak_turns:
        model_leaks: dict[str, int] = {}
        model_turn_counts: dict[str, int] = {}
        for t in leak_turns:
            key = t.model or "unknown"
            model_leaks[key] = model_leaks.get(key, 0) + len(t.leakage_instances)
            model_turn_counts[key] = model_turn_counts.get(key, 0) + 1
        html += "<h3>Leakage by Model</h3><table><tr><th>Model</th>"
        html += "<th class='num'>Leak Instances</th><th class='num'>Turns Affected</th></tr>"
        for model, count in sorted(model_leaks.items(), key=lambda x: -x[1]):
            html += f"<tr><td>{_esc(model)}</td><td class='num'>{count}</td>"
            html += f"<td class='num'>{model_turn_counts[model]}</td></tr>"
        html += "</table>"

    return html


def render_performance(report: PerformanceReport) -> str:
    d = performance_to_dict(report)
    html = f'<h2>Layer 4: Performance \u2014 {_esc(report.session_key)}</h2><div class="card">'
    metrics = [
        ("Calls", d["total_calls"]),
        ("With Timing", d["calls_with_duration"]),
        ("Avg Latency", f"{d['avg_latency_ms']:.0f}ms"),
        ("Avg tok/s", f"{d['avg_throughput_tps']:.1f}"),
        ("Cache Hit", pct(d["overall_cache_hit_rate"])),
    ]
    for label, val in metrics:
        html += f'<div class="metric"><div class="label">{label}</div><div class="value">{val}</div></div>'
    html += "</div>"

    if d["by_model"]:
        html += "<h3>By Model</h3><table><tr><th>Model</th><th class='num'>Calls</th>"
        html += "<th class='num'>Avg Lat.</th><th class='num'>p50</th><th class='num'>p95</th>"
        html += "<th class='num'>p99</th><th class='num'>Avg tok/s</th><th class='num'>Cache Hit</th></tr>"
        for model, mp in d["by_model"].items():
            html += f"<tr><td>{_esc(model)}</td><td class='num'>{mp['call_count']}</td>"
            html += f"<td class='num'>{mp['avg_latency_ms']:.0f}ms</td>"
            html += f"<td class='num'>{mp['p50_latency_ms']:.0f}ms</td>"
            html += f"<td class='num'>{mp['p95_latency_ms']:.0f}ms</td>"
            html += f"<td class='num'>{mp['p99_latency_ms']:.0f}ms</td>"
            html += f"<td class='num'>{mp['avg_throughput_tps']:.1f}</td>"
            html += f"<td class='num'>{pct(mp['cache_hit_rate'])}</td></tr>"
        html += "</table>"

    return html


